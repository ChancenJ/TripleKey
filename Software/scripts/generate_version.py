"""Pre-build script: reads VERSION file and generates version_generated.h."""
Import("env")
import os

project_dir = env["PROJECT_DIR"]
version_file = os.path.join(project_dir, "VERSION")
output_file = os.path.join(project_dir, "src", "version_generated.h")

with open(version_file, "r") as f:
    version = f.read().strip()

content = '// Auto-generated by scripts/generate_version.py, DO NOT EDIT\n'
content += '#ifndef __VERSION_GENERATED_H\n'
content += '#define __VERSION_GENERATED_H\n'
content += f'#define VER_SW "{version}"\n'
content += '#endif\n'

with open(output_file, "w") as f:
    f.write(content)

print(f"[generate_version] VER_SW = {version}")
